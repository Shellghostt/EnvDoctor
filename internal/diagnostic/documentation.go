package diagnostic

import (
	"fmt"
	"strings"
)

// RuleMarkdown is the full offline explanation and the reproducible rule page.
func RuleMarkdown(rule RuleMetadata) string {
	var text strings.Builder
	fmt.Fprintf(&text, "# %s: %s\n\n", rule.RuleID, rule.Title)
	text.WriteString("<!-- Code generated by cmd/rulegen from the builtin registry. DO NOT EDIT. -->\n\n")
	fmt.Fprintf(&text, "Component: %s. Severity: %s.\n\n", rule.Component, rule.Severity)
	fmt.Fprintf(&text, "Collector prerequisites: %s.\n\n", strings.Join(rule.Prerequisites, ", "))
	fmt.Fprintf(&text, "%s\n\nEvidence required: %s\n\n", rule.Explanation, rule.Evidence)
	text.WriteString("Manual steps:\n\n")
	for _, step := range rule.ManualSteps {
		fmt.Fprintf(&text, "- %s\n", step)
	}
	fmt.Fprintf(&text, "\nVerify with `%s`.\n\nLimitations:\n\n", rule.Verify)
	for _, caveat := range rule.Caveats {
		fmt.Fprintf(&text, "- %s\n", caveat)
	}
	text.WriteString("\nNo command is executed by this rule. Evidence comes only from the snapshot. Failed prerequisite collectors disable the rule. Positive, negative and edge fixtures cover Windows, Linux and macOS; platform exclusions are listed above.\n\n")
	fmt.Fprintf(&text, "Documentation: <%s>.\n", rule.Docs)
	return text.String()
}
